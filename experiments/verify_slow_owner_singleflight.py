"""Verification script: Slow owner single-flight memoization without duplicate noise (Audit C11).

Demonstrates that an in-flight computation taking >10 seconds (e.g. 11 seconds) does NOT
cause concurrent workers to abort the active owner or generate duplicate independent noise.

Verifies:
  1. Worker A reserves and computes with an intentional delay (>10s).
  2. Concurrent Worker B waits for Worker A rather than prematurely aborting it.
  3. Worker A commits successfully.
  4. Worker B receives the memoized payload generated by Worker A (Cache Hit).
  5. Both workers return bitwise identical DP results.
  6. Exactly 1 committed reservation and 1 committed release exist in persistent state.
  7. Privacy budget is charged exactly once (epsilon=1.0, NOT 2.0).
"""

from concurrent.futures import ProcessPoolExecutor
from datetime import datetime, timezone
from pathlib import Path
import sys
import time
import numpy as np

# Ensure project root is in sys.path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from private_llm_analytics.aggregation.user_matrix import (
    UserMatrix,
    build_cell_definitions,
)
from private_llm_analytics.config.loader import load_app_config
from private_llm_analytics.planner.query import AnalyticsQuery
from private_llm_analytics.privacy.state import PrivacyStateManager
from private_llm_analytics.release.release import ReleaseOrchestrator


def make_test_user_matrix() -> UserMatrix:
    provs = ["provider_a", "provider_b", "provider_c"]
    tsks = ["technical", "document", "analysis"]
    cell_names, cell_map = build_cell_definitions(provs, tsks)
    np_matrix = np.ones((10, 9), dtype=np.float64) * 25.0
    return UserMatrix(
        matrix=np_matrix,
        user_ids=[f"U{i}" for i in range(10)],
        providers=provs,
        tasks=tsks,
        cell_names=cell_names,
        cell_map=cell_map,
        public_population_size=50000,
    )


def slow_worker_task(db_path_str: str, worker_id: str, delay_seconds: float):
    """Worker task that can intentionally introduce delay during computation."""
    config = load_app_config("configs")
    # Single-flight timeout set to 30.0s (sufficient for slow worker)
    config.privacy.release.single_flight_timeout = 30.0
    config.privacy.release.lease_timeout = 300.0

    state_mgr = PrivacyStateManager(db_path_str)
    hooks = {}
    if delay_seconds > 0:
        def delay_hook():
            print(f"[{datetime.now(timezone.utc).strftime('%H:%M:%S')}] Worker {worker_id}: intentionally sleeping {delay_seconds}s after reserve...")
            time.sleep(delay_seconds)
            print(f"[{datetime.now(timezone.utc).strftime('%H:%M:%S')}] Worker {worker_id}: woke up from {delay_seconds}s sleep; resuming commit.")
        hooks["after_budget_reserve"] = delay_hook

    orch = ReleaseOrchestrator(app_config=config, state_manager=state_mgr, test_hooks=hooks)
    u_mat = make_test_user_matrix()

    query = AnalyticsQuery(
        metric="user_normalized_share",
        recipient="internal",
        epsilon=1.0,
        delta=1e-6,
    )

    t0 = time.time()
    try:
        print(f"[{datetime.now(timezone.utc).strftime('%H:%M:%S')}] Worker {worker_id}: starting execute_release...")
        res = orch.execute_release(query, u_mat, dataset_version="audit_v013_dataset")
        elapsed = time.time() - t0
        print(f"[{datetime.now(timezone.utc).strftime('%H:%M:%S')}] Worker {worker_id}: completed in {elapsed:.2f}s (cache_hit={res['cache_hit']}).")
        return {
            "worker_id": worker_id,
            "status": "SUCCESS",
            "cache_hit": res["cache_hit"],
            "release_key": res["release_key"],
            "cell_shares": res["results"]["cell_shares"],
            "elapsed": elapsed,
            "error": None,
        }
    except Exception as exc:
        elapsed = time.time() - t0
        print(f"[{datetime.now(timezone.utc).strftime('%H:%M:%S')}] Worker {worker_id}: FAILED after {elapsed:.2f}s: {exc}")
        return {
            "worker_id": worker_id,
            "status": "ERROR",
            "elapsed": elapsed,
            "error": f"{type(exc).__name__}: {str(exc)}",
        }


def delayed_submittal(executor, db_path_str: str, worker_id: str, delay_seconds: float, start_offset: float):
    if start_offset > 0:
        time.sleep(start_offset)
    return executor.submit(slow_worker_task, db_path_str, worker_id, delay_seconds)


def main():
    print("=" * 70)
    print("VERIFICATION: Slow Owner Single-Flight Memoization (Audit C11)")
    print("=" * 70)

    test_db = Path("results/verify_slow_owner_singleflight.db")
    for f in [test_db, Path("results/verify_slow_owner_singleflight_cache.db"), Path("results/verify_slow_owner_singleflight_ledger.db")]:
        if f.exists():
            f.unlink(missing_ok=True)
    for ext in ["-wal", "-shm", ".jsonl"]:
        p = Path(str(test_db) + ext)
        if p.exists():
            p.unlink(missing_ok=True)

    state_mgr = PrivacyStateManager(test_db)
    state_mgr.clear()

    print("Launching Worker A (deliberate 11.0s slow computation) and Worker B (starts at t=0.3s)...")
    with ProcessPoolExecutor(max_workers=2) as executor:
        fut_a = executor.submit(slow_worker_task, str(test_db), "Worker_A", 11.0)
        # Worker B starts 0.3s after Worker A
        time.sleep(0.3)
        fut_b = executor.submit(slow_worker_task, str(test_db), "Worker_B", 0.0)

        res_a = fut_a.result()
        res_b = fut_b.result()

    print("\nWorker Execution Summary:")
    print(f"  Worker A Status: {res_a['status']}, Cache Hit: {res_a.get('cache_hit')}, Elapsed: {res_a.get('elapsed', 0):.2f}s")
    print(f"  Worker B Status: {res_b['status']}, Cache Hit: {res_b.get('cache_hit')}, Elapsed: {res_b.get('elapsed', 0):.2f}s")

    assert res_a["status"] == "SUCCESS", f"Worker A failed: {res_a.get('error')}"
    assert res_b["status"] == "SUCCESS", f"Worker B failed: {res_b.get('error')}"
    assert res_a["cache_hit"] is False, "Worker A should be the generator (cache_hit=False)"
    assert res_b["cache_hit"] is True, "Worker B should be memoized from Worker A (cache_hit=True)"

    # Verify identical results
    shares_a = res_a["cell_shares"]
    shares_b = res_b["cell_shares"]
    for k in shares_a:
        diff = abs(shares_a[k] - shares_b[k])
        assert diff == 0.0, f"Cell share mismatch on '{k}': {shares_a[k]} vs {shares_b[k]}"
    print("  DP Results: BITWISE IDENTICAL between Worker A and Worker B.")

    # Verify persistent database state
    spent_eps, spent_del = state_mgr.get_total_spent()
    print(f"\nAuthoritative Database Audit:")
    print(f"  Total Committed Spent Epsilon: {spent_eps:.4f} (Expected: exactly 1.0000)")
    print(f"  Total Committed Spent Delta:   {spent_del:.2e} (Expected: exactly 1.00e-06)")

    assert abs(spent_eps - 1.0) < 1e-9, f"Budget overspent! {spent_eps} != 1.0"
    assert abs(spent_del - 1e-6) < 1e-12, f"Delta overspent! {spent_del} != 1e-6"

    with state_mgr._connection() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT COUNT(*) FROM privacy_reservations WHERE status = 'COMMITTED'")
        comm_res = cursor.fetchone()[0]
        cursor.execute("SELECT COUNT(*) FROM release_store WHERE status = 'COMMITTED'")
        comm_rel = cursor.fetchone()[0]

    print(f"  Committed Reservations in DB: {comm_res} (Expected: 1)")
    print(f"  Committed Releases in DB:     {comm_rel} (Expected: 1)")

    assert comm_res == 1, f"Expected 1 committed reservation, found {comm_res}"
    assert comm_rel == 1, f"Expected 1 committed release, found {comm_rel}"

    print("\n[VERIFICATION PASSED] Slow owner single-flight prevents duplicate noise and guarantees single charge.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
